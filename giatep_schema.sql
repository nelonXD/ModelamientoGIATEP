  FOREIGN KEY (`Id_Clasificacion_Caso`) REFERENCES `TIPO_CASO` (`Id_Clasificacion_Caso`) ON DELETE RESTRICT ON UPDATE CASCADE,
  FOREIGN KEY (`RUT_Usuario`) REFERENCES `USUARIO` (`Rut_Usuario`) ON DELETE RESTRICT ON UPDATE CASCADE,
  FOREIGN KEY (`Id_Empresa`) REFERENCES `EMPRESA_EMPLEADOR` (`Id_Empresa`) ON DELETE RESTRICT ON UPDATE CASCADE
