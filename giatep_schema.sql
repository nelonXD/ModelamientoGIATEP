CREATE DATABASE IF NOT EXISTS `giatep_db` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `giatep_db`;
SET NAMES utf8mb4;

CREATE TABLE `REGION` (
  `Id_Region` INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `Nombre_Region` VARCHAR(100) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `COMUNA` (
  `Id_Comuna` INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `Id_Region` INT NOT NULL,
  `Nombre_Comuna` VARCHAR(100) NOT NULL,
  FOREIGN KEY (`Id_Region`) REFERENCES `REGION` (`Id_Region`) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `DEPENDENCIA` (
  `Id_Dependencia` INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `Nombre_Dependencia` VARCHAR(150) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `PUEBLOS_ORIGINARIOS` (
  `Id_Pueblo_Originario` INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `Nombre_Pueblo` VARCHAR(100) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `ROL` (
  `Id_Rol` INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `Nombre_Rol` VARCHAR(50) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `PERMISOS` (
  `Id_Permiso` INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `Nombre_Permiso` VARCHAR(100) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `USUARIO` (
  `Rut_Usuario` VARCHAR(12) NOT NULL PRIMARY KEY,
  `Contrasena_Hash` VARCHAR(255) NOT NULL,
  `Correo` VARCHAR(254) NOT NULL,
  `Id_Dependencia` INT NOT NULL,
  FOREIGN KEY (`Id_Dependencia`) REFERENCES `DEPENDENCIA` (`Id_Dependencia`) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `ROL_USUARIO` (
  `Id_Rol_Us` INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `Id_Rol` INT NOT NULL,
  `Rut_Usuario` VARCHAR(12) NOT NULL,
  UNIQUE (`Id_Rol`, `Rut_Usuario`),
  FOREIGN KEY (`Id_Rol`) REFERENCES `ROL` (`Id_Rol`) ON DELETE RESTRICT ON UPDATE CASCADE,
  FOREIGN KEY (`Rut_Usuario`) REFERENCES `USUARIO` (`Rut_Usuario`) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `ROL_PERMISOS` (
  `Id_Rol_Per` INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `Id_Rol` INT NOT NULL,
  `Id_Permiso` INT NOT NULL,
  UNIQUE (`Id_Rol`, `Id_Permiso`),
  FOREIGN KEY (`Id_Rol`) REFERENCES `ROL` (`Id_Rol`) ON DELETE RESTRICT ON UPDATE CASCADE,
  FOREIGN KEY (`Id_Permiso`) REFERENCES `PERMISOS` (`Id_Permiso`) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `SOLICITUD_ACCESO` (
  `Id_Solicitud` INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `Rut_Solicitante` VARCHAR(12) NOT NULL,
  `Nombre_Solicitante` VARCHAR(150) NOT NULL,
  `Correo_Solicitante` VARCHAR(254) NOT NULL,
  `Id_Rol_Solicitado` INT NOT NULL,
  `Motivo_Solicitud` TEXT,
  `Fecha_Solicitud` DATETIME NOT NULL,
