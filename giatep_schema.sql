  FOREIGN KEY (`Id_Pueblo_Originario`) REFERENCES `PUEBLOS_ORIGINARIOS` (`Id_Pueblo_Originario`) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `TIPO_CASO` (
  `Id_Clasificacion_Caso` INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `Nombre_Tipo_Caso` VARCHAR(100) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

