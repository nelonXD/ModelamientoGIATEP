  FOREIGN KEY (`Rut_Usuario_Validador`) REFERENCES `USUARIO` (`Rut_Usuario`) ON DELETE RESTRICT ON UPDATE CASCADE,
  FOREIGN KEY (`Rut_Usuario_Beneficiario`) REFERENCES `USUARIO` (`Rut_Usuario`) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `COMITE_PARITARIO` (
  `Id_Comite` INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `Fecha_Inicio` DATE NOT NULL,
  `Fecha_Termino` DATE NULL,
  `Id_Dependencia` INT NOT NULL,
  `Rut_Usuario` VARCHAR(12) NOT NULL,
  FOREIGN KEY (`Id_Dependencia`) REFERENCES `DEPENDENCIA` (`Id_Dependencia`) ON DELETE RESTRICT ON UPDATE CASCADE,
  FOREIGN KEY (`Rut_Usuario`) REFERENCES `USUARIO` (`Rut_Usuario`) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

