  FOREIGN KEY (`Id_Dependencia`) REFERENCES `DEPENDENCIA` (`Id_Dependencia`) ON DELETE RESTRICT ON UPDATE CASCADE,
  FOREIGN KEY (`Rut_Usuario`) REFERENCES `USUARIO` (`Rut_Usuario`) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `EMPRESA_EMPLEADOR` (
  `Id_Empresa` INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `Nombre_Empresa` VARCHAR(150) NOT NULL,
  `Centro_Trabajo` VARCHAR(150),
  `Organismo_Administrador` VARCHAR(20),
  `Direccion_Sucursal` VARCHAR(255),
